// Command artifacthub writes the artifacthub.io/crds and
// artifacthub.io/crdsExamples annotations of the karpenter-crd chart from the
// shipped CRDs, so Artifact Hub lists every CRD with its storage version. Run
// it from the repository root through `make update`.
//
// The approach follows the generators in
// https://github.com/stackabletech/hive-operator/blob/main/Makefile and
// https://github.com/crenshaw-dev/gitops-promoter-helm/blob/main/hack/update-artifacthub-crd-annotations.sh.
// Annotation format: https://artifacthub.io/docs/topics/annotations/helm/
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"sigs.k8s.io/yaml"
)

const (
	crdGlob   = "charts/karpenter/crds/*.yaml"
	chartPath = "charts/karpenter-crd/Chart.yaml"

	// The generated annotations live between these markers in Chart.yaml.
	beginMarker = "  # BEGIN generated by hack/artifacthub (make update); do not edit\n"
	endMarker   = "  # END generated by hack/artifacthub\n"
)

// examples are embedded verbatim, at most one per CRD.
var examples = []string{
	"examples/nodeclass/default-gcenodeclass.yaml",
	"examples/nodepool/default-nodepool.yaml",
}

type card struct {
	Kind        string `json:"kind"`
	Version     string `json:"version"`
	Name        string `json:"name"`
	DisplayName string `json:"displayName"`
	Description string `json:"description"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "artifacthub:", err)
		os.Exit(1)
	}
}

func run() error {
	files, err := filepath.Glob(crdGlob)
	if err != nil || len(files) == 0 {
		return fmt.Errorf("no CRDs match %s: %v", crdGlob, err)
	}
	var cards []card
	for _, f := range files {
		c, err := readCard(f)
		if err != nil {
			return err
		}
		cards = append(cards, c)
	}
	crds, err := yaml.Marshal(cards)
	if err != nil {
		return err
	}
	var sample strings.Builder
	for _, f := range examples {
		data, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		sample.WriteString(asListItem(string(data)))
	}

	block := literal("artifacthub.io/crds", string(crds)) +
		literal("artifacthub.io/crdsExamples", sample.String())
	chart, err := os.ReadFile(chartPath)
	if err != nil {
		return err
	}
	out, err := replaceBlock(string(chart), block)
	if err != nil {
		return err
	}
	return os.WriteFile(chartPath, []byte(out), 0o600) // mode only matters if the file is created; Chart.yaml exists
}

// readCard builds the card from the CRD's storage version. The description is
// the first paragraph of the schema description on one line, or "<Kind> custom
// resource" when the CRD has none.
func readCard(path string) (card, error) {
	var crd struct {
		Metadata struct{ Name string } `json:"metadata"`
		Spec     struct {
			Names    struct{ Kind string } `json:"names"`
			Versions []struct {
				Name    string `json:"name"`
				Storage bool   `json:"storage"`
				Schema  struct {
					OpenAPIV3Schema struct{ Description string } `json:"openAPIV3Schema"`
				} `json:"schema"`
			} `json:"versions"`
		} `json:"spec"`
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return card{}, err
	}
	if err := yaml.Unmarshal(data, &crd); err != nil {
		return card{}, fmt.Errorf("%s: %w", path, err)
	}
	for _, v := range crd.Spec.Versions {
		if !v.Storage {
			continue
		}
		kind := crd.Spec.Names.Kind
		desc, _, _ := strings.Cut(strings.TrimSpace(v.Schema.OpenAPIV3Schema.Description), "\n\n")
		if desc = strings.Join(strings.Fields(desc), " "); desc == "" {
			desc = kind + " custom resource"
		}
		return card{Kind: kind, Version: v.Name, Name: crd.Metadata.Name, DisplayName: kind, Description: desc}, nil
	}
	return card{}, fmt.Errorf("%s: no storage version", path)
}

// asListItem turns one YAML mapping into a list item: "- " on the first line
// and a two-space indent on the rest.
func asListItem(mapping string) string {
	lines := strings.Split(strings.TrimRight(mapping, "\n"), "\n")
	for i, l := range lines {
		switch {
		case i == 0:
			lines[i] = "- " + l
		case l != "":
			lines[i] = "  " + l
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

// literal renders `key: |` followed by body as an indented literal block.
func literal(key, body string) string {
	var b strings.Builder
	b.WriteString("  " + key + ": |\n")
	for _, l := range strings.Split(strings.TrimRight(body, "\n"), "\n") {
		if l != "" {
			l = "    " + l
		}
		b.WriteString(l + "\n")
	}
	return b.String()
}

// replaceBlock swaps the text between the markers for block.
func replaceBlock(chart, block string) (string, error) {
	start := strings.Index(chart, beginMarker)
	end := strings.Index(chart, endMarker)
	if start < 0 || end < start {
		return "", fmt.Errorf("%s: missing generated-block markers", chartPath)
	}
	return chart[:start+len(beginMarker)] + block + chart[end:], nil
}
